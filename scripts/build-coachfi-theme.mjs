// Generates styles/coachfi/channels.css from the design tokens.
// Tailwind opacity modifiers (bg-primary/10) need colours as RGB channels, so every
// --cf-<token> hex gets a --cf-<token>-rgb twin. Run: node scripts/build-coachfi-theme.mjs
import { readFileSync, writeFileSync } from "node:fs";

const tokens = JSON.parse(
  readFileSync(new URL("../design/coachfi-design-system/tokens/tokens.json", import.meta.url), "utf8")
);

// The pre-v6 palette, expressed with the same token names, so the old look can be
// switched back on with data-theme="legacy" (NEXT_PUBLIC_DESIGN_V6=0).
const legacy = {
  bg: "#F8FAFF",
  surface: "#FFFFFF",
  "surface-brand": "#F3F5FF",
  text: "#26324A",
  "text-muted": "#66758F",
  primary: "#7668E8",
  "primary-border": "#7668E8",
  "primary-strong": "#6558D6",
  "primary-soft": "#EEF2FF",
  "on-primary": "#FFFFFF",
  grape: "#7668E8",
  "on-grape": "#FFFFFF",
  accent: "#F6A66D",
  "on-accent": "#26324A",
  "area-learn": "#7DD3DC",
  "area-goals": "#F6A66D",
  "area-progress": "#A8E6CF",
  "area-mila": "#EEF2FF",
  "area-rewards": "#F7DFA6",
  "area-care": "#F6A66D",
  "on-area": "#26324A",
  "on-goals-strong": "#26324A",
  attention: "#F6A66D",
  border: "#C9CEE8",
  "border-subtle": "#E6E8F5",
  focus: "#7668E8",
  "chart-1": "#7668E8",
  "chart-2": "#7DD3DC",
  "chart-3": "#F6A66D",
  "chart-highlight": "#F6A66D",
};

const isHex = (value) => /^#[0-9a-f]{6}$/i.test(value);
const channels = (hex) =>
  [1, 3, 5].map((start) => parseInt(hex.slice(start, start + 2), 16)).join(" ");

function block(selector, theme, withHex) {
  const lines = [];
  for (const [name, value] of Object.entries(theme)) {
    if (typeof value !== "string" || !isHex(value)) continue;
    if (withHex) lines.push(`  --cf-${name}: ${value.toUpperCase()};`);
    lines.push(`  --cf-${name}-rgb: ${channels(value)};`);
  }
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

const { themes } = tokens;
const out = [
  "/* GENERATED by scripts/build-coachfi-theme.mjs from design/coachfi-design-system/tokens/tokens.json — do not edit. */",
  block(':root, [data-theme="adult-light"]', themes["adult-light"], false),
  ...["adult-dark", "teen", "kids", "high-contrast"].map((name) =>
    block(`[data-theme="${name}"]`, themes[name], false)
  ),
  block('[data-theme="legacy"]', legacy, true),
].join("\n");

writeFileSync(new URL("../styles/coachfi/channels.css", import.meta.url), out);
console.log("styles/coachfi/channels.css written");
