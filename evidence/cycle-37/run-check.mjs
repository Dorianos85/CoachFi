import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
const repo = fs.realpathSync(process.cwd());
const require = createRequire(path.join(repo,'package.json'));
const mode = process.argv[2];
const newTests=['tests/cycle37-risk-protection-financial.test.ts','tests/cycle37-risk-protection-ui.test.ts'];
const legacyAllowed=['tests/cycle6-mindset-author.test.ts','tests/cycle6-quiz-review.test.ts','tests/cycle11-saving-author.test.ts','tests/cycle15-inflation-author.test.ts','tests/cycle16-credit-author.test.ts','tests/cycle17-emergency-author.test.ts'];
const selected=mode==='baseline'||mode==='acceptance'?newTests:[];
if(!['baseline','acceptance','typecheck'].includes(mode))throw Error('Unknown check');
const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(path.join(repo,p))).digest('hex');
const extraPinned=mode==='typecheck'?[...legacyAllowed,'tests/cycle37-legacy-preservation.ts','tests/e2e/risk-protection-content.spec.ts','playwright.cycle37.config.ts']:[];
const checkedPaths=[...new Set(['data/quizQuestions.ts','lib/allQuestions.ts',...newTests,...extraPinned])].filter(p=>fs.existsSync(path.join(repo,p)));
const before=checkedPaths.map(p=>({path:p,sha256:sha(p)}));
const env={...process.env};
for(const n of Object.keys(env))if(/SUPABASE|CDP_|SOLANA|ANTHROPIC|OPENAI|OPENROUTER|ELEVENLABS|UPSTASH|COACHFI_DEV_DB/.test(n))env[n]='';
env.NEXT_TELEMETRY_DISABLED='1';
const args=mode==='typecheck'?[require.resolve('typescript/bin/tsc'),'--noEmit','--incremental','false']:[path.join(path.dirname(require.resolve('vitest/package.json')),'vitest.mjs'),'run',...selected,'--maxWorkers=2','--reporter=verbose','--reporter=json','--outputFile=evidence/cycle-37/'+mode+'-tests.json'];
const startedAt=new Date().toISOString();
const result=spawnSync(process.execPath,args,{cwd:repo,env,encoding:'utf8',shell:false,maxBuffer:10*1024*1024});
const after=checkedPaths.map(p=>({path:p,sha256:sha(p)}));
const sourceOrFixtureMismatches=before.filter((v,i)=>v.sha256!==after[i].sha256);
const report={mode,startedAt,completedAt:new Date().toISOString(),childExitCode:result.status,exitCode:result.status===0&&sourceOrFixtureMismatches.length?1:result.status,selectedTests:selected,before,after,sourceOrFixtureMismatches,environment:'provider/auth env blank; telemetry off; synthetic/local only',stdout:result.stdout??'',stderr:result.stderr??'',error:result.error?.message??null};
fs.writeFileSync(path.join(repo,'evidence/cycle-37/'+mode+'-run.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({mode,exitCode:report.exitCode,mismatches:report.sourceOrFixtureMismatches,error:report.error}));
process.exitCode=report.exitCode??1;
